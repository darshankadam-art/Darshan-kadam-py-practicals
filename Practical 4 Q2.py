# Print numbers using a for loop
print("Using for loop:")

for i in range(1, 11):
    # Display the current number
    print(i)

# Print numbers using a while loop
print("\nUsing while loop:")

i = 1

# Continue while i is less than or equal to 10
while i <= 10:
    print(i)

    # Increase i so the loop eventually stops
    i += 1
