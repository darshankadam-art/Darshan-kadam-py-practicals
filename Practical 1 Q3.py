# Practical 1 - Q3: Constants Simulation
# Uppercase names are a convention for values intended as constants.
PI = 3.14159
GRAVITY = 9.81
MAX_USERS = 100
print("PI:", PI)
print("GRAVITY:", GRAVITY)
print("MAX_USERS:", MAX_USERS)

# Python does not enforce constants; reassignment is permitted.
PI = 3.14
print("PI after reassignment:", PI)
# Constant-like behavior relies on convention: avoid reassignment.
