# Print numbers from 1 to 10
print("Numbers from 1 to 10:")

# range(1, 11) generates numbers from 1 through 10
for i in range(1, 11):
    print(i)

# Print only even numbers from 1 to 10
print("\nEven numbers from 1 to 10:")

# Start at 2 and increase by 2 each time
for i in range(2, 11, 2):
    print(i)

