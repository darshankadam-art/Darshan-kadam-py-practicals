# Create a list and a tuple
numbers_list = [10, 20, 30, 40, 50, 60]
numbers_tuple = (10, 20, 30, 40, 50, 60)

# Slice the list
print("List - first 3:", numbers_list[:3])
print("List - last 2:", numbers_list[-2:])
print("List - alternate:", numbers_list[::2])

# Slice the tuple
print("Tuple - first 3:", numbers_tuple[:3])
print("Tuple - last 2:", numbers_tuple[-2:])
print("Tuple - alternate:", numbers_tuple[::2])
