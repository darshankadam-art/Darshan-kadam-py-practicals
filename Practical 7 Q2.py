# Create a list and a tuple
numbers = [10, 20, 30, 40, 50]
values = (10, 20, 30, 40, 50)

# Access elements using positive indexing
print("List first element:", numbers[0])
print("List middle element:", numbers[2])
print("List last element:", numbers[4])

# Access elements using negative indexing
print("List last using negative index:", numbers[-1])
print("List first using negative index:", numbers[-5])

# Access elements in the tuple
print("Tuple first element:", values[0])
print("Tuple middle element:", values[2])
print("Tuple last element:", values[-1])
